-- AccessAble starter schema for Supabase PostgreSQL.
-- Run in Supabase SQL Editor on a DEVELOPMENT project.
-- This script creates the tables and inserts a small, fictional sample campus.
-- Do not paste production passwords or API keys into this file.

CREATE TABLE IF NOT EXISTS buildings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    campus_zone VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS facilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id BIGINT NOT NULL REFERENCES buildings(id),
    name VARCHAR(120) NOT NULL,
    facility_type VARCHAR(40) NOT NULL CHECK (facility_type IN (
        'LIFT', 'RAMP', 'STEP_FREE_ENTRANCE', 'ACCESSIBLE_RESTROOM', 'ACCESSIBLE_ROUTE', 'OTHER'
    )),
    floor_label VARCHAR(30) NOT NULL DEFAULT 'Ground',
    description VARCHAR(500),
    current_status VARCHAR(40) NOT NULL DEFAULT 'UNKNOWN' CHECK (current_status IN (
        'AVAILABLE', 'TEMPORARILY_UNAVAILABLE', 'UNDER_MAINTENANCE', 'UNKNOWN'
    )),
    last_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (building_id, name, floor_label)
);

CREATE TABLE IF NOT EXISTS status_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id BIGINT NOT NULL REFERENCES facilities(id),
    issue_type VARCHAR(40) NOT NULL CHECK (issue_type IN (
        'OUT_OF_SERVICE', 'ROUTE_BLOCKED', 'ACCESS_BLOCKED', 'FACILITY_UNAVAILABLE', 'OTHER'
    )),
    description VARCHAR(1000) NOT NULL,
    suggested_status VARCHAR(40) NOT NULL CHECK (suggested_status IN (
        'TEMPORARILY_UNAVAILABLE', 'UNDER_MAINTENANCE'
    )),
    report_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (report_status IN (
        'PENDING', 'VERIFIED', 'REJECTED', 'RESOLVED'
    )),
    reported_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ,
    admin_note VARCHAR(500)
);

CREATE INDEX IF NOT EXISTS idx_facilities_building_id ON facilities(building_id);
CREATE INDEX IF NOT EXISTS idx_facilities_type ON facilities(facility_type);
CREATE INDEX IF NOT EXISTS idx_facilities_status ON facilities(current_status);
CREATE INDEX IF NOT EXISTS idx_reports_status ON status_reports(report_status);
CREATE INDEX IF NOT EXISTS idx_reports_facility_id ON status_reports(facility_id);

-- Enable Row Level Security to prevent accidental anonymous/authenticated access
-- through Supabase's Data API. AccessAble reads/writes through the Java backend.
-- Do not add broad public policies to these tables for this architecture.
ALTER TABLE buildings ENABLE ROW LEVEL SECURITY;
ALTER TABLE facilities ENABLE ROW LEVEL SECURITY;
ALTER TABLE status_reports ENABLE ROW LEVEL SECURITY;

