INSERT INTO facilities
    (building_id, name, facility_type, floor_label, description, current_status, last_verified_at)
SELECT b.id, v.name, v.facility_type, v.floor_label, v.description, v.current_status,
       CASE WHEN v.current_status = 'UNKNOWN' THEN NULL ELSE NOW() END
FROM buildings b
JOIN (VALUES
    ('Main step-free entrance', 'STEP_FREE_ENTRANCE', 'Ground', 'Ramp at the main entrance.', 'AVAILABLE'),
    ('Passenger lift', 'LIFT', 'Ground to Floor 3', 'Lift serving the main floors.', 'AVAILABLE'),
    ('Accessible washroom', 'ACCESSIBLE_RESTROOM', 'Ground', 'Near the main corridor.', 'UNKNOWN'),
    ('Library entrance ramp', 'RAMP', 'Ground', 'Ramp beside the west entrance.', 'AVAILABLE'),
    ('Library lift', 'LIFT', 'Ground to Floor 2', 'Lift near the circulation desk.', 'UNDER_MAINTENANCE'),
    ('Student centre step-free route', 'ACCESSIBLE_ROUTE', 'Ground', 'Route from the courtyard entrance.', 'AVAILABLE')
) AS v(name, facility_type, floor_label, description, current_status) ON TRUE
WHERE b.name = CASE
    WHEN v.name IN ('Library entrance ramp', 'Library lift') THEN 'Library Block'
    WHEN v.name = 'Student centre step-free route' THEN 'Student Centre'
    ELSE 'Academic Block A'
END
ON CONFLICT (building_id, name, floor_label) DO NOTHING;
