package com.accessable.model;

import org.junit.jupiter.api.Test;
import static org.junit.jupiter.api.Assertions.*;

/**
 * Plain JUnit test for the Building entity. No database is needed — it only checks
 * that the fields, getters and setters behave as a student would expect.
 */
class BuildingTest {

    @Test
    void gettersAndSettersWork() {
        Building building = new Building();
        building.setId(1L);
        building.setName("Academic Block A");
        building.setCampusZone("North Campus");

        assertEquals(1L, building.getId());
        assertEquals("Academic Block A", building.getName());
        assertEquals("North Campus", building.getCampusZone());
        assertNull(building.getCreatedAt());
    }

    @Test
    void allArgsConstructorSetsFields() {
        Building building = new Building("Library Block", "Central Campus");
        assertEquals("Library Block", building.getName());
        assertEquals("Central Campus", building.getCampusZone());
        assertNull(building.getId()); // id is generated by the database
    }
}